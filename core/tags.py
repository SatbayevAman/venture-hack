def question_for(first_error: dict, lang: str = "ru") -> str:
    tag = first_error["tag"]
    det = first_error.get("detail") or {}
    key = tag
    if tag == "lost_root" and det.get("division"):
        key = "lost_root_div"
    elif tag == "lost_root" and det.get("pm"):
        key = "lost_root_pm"
    elif tag == "subst" and det.get("change"):
        key = "subst_change"
    elif tag == "extra_root" and det.get("domain"):
        key = "extra_root_domain"
    elif tag == "calc" and det.get("num"):
        key = "calc_num"
    elif tag == "ineq_div_var" and det.get("mul"):
        key = "ineq_div_var_mul"
    elif tag == "boundary" and det.get("domain"):
        key = "boundary_domain"
    tpl = QUESTIONS.get(key, QUESTIONS["other"])[lang]
    fields = {"n": first_error["line"], **det, **{k: v for k, v in first_error.items() if k.startswith("P_")}}
    try:
        return tpl.format(**fields)
    except (KeyError, IndexError):
        return QUESTIONS["other"][lang].format(**fields)


