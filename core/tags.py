def tag_comment_keywords(text: str) -> list[dict]:
    """Разметка комментария учителя по словарю основ. → [{tag, quote}]"""
    import re
    low = text.lower()
    out = []
    # цитата — фрагмент между знаками препинания, где встретилась основа слова
    bounds = [0] + [m.end() for m in re.finditer(r"[.!?;,:—–]\s*", text)] + [len(text)]
    for tag, stems in LEXICON:
        for st in stems:
            idx = low.find(st)
            if idx >= 0:
                if tag == "good_progress" and ("не " + st in low or "не очень " + st in low):
                    continue
                a = max(b for b in bounds if b <= idx)
                b = min(b for b in bounds if b > idx)
                quote = text[a:b].strip(" ,.;:—–!?")
                out.append({"tag": tag, "quote": quote or text.strip()})
                break
    if not out:
        out.append({"tag": "teacher_other", "quote": text.strip()[:80]})
    return out
