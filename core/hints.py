def rule(tag: str, lang: str = "ru") -> str:
    """Правило для тега; неизвестный тег (новые темы) — общее правило «проверь подстановкой»."""
    return RULES.get(tag, GENERIC_RULE)[lang]


def _seed(statement: str) -> int:
    return zlib.crc32(statement.encode("utf-8"))


def example(first_error: dict, statement: str, skill: Optional[str], seed: Optional[int] = None,
            family: Optional[str] = None) -> Optional[dict]:
    """Ступень 3 как данные: задача, строки, ключевая строка и пометка (ru/kk).

    family — семья шаблонов задачи ученика (тег, который тренируем); без неё — по тегу ошибки.
    Пример — всегда другая задача; если можно, берём такой, в котором не встречаются корни задачи ученика."""
    tag = family if family in practice.FAMILIES else (first_error.get("tag") or "other")
    base = _seed(statement) if seed is None else seed
    own = _true_values(statement)
    first = None
    for k in range(12):
        ex = practice.worked_example(tag, skill, avoid=statement, seed=base + k)
        if ex is None:
            break
        first = first or ex
        if not {round(v, 9) for v in _values(ex["answer"])} & {round(float(v), 9) for v in own}:
            return ex
    return first


def _true_values(statement: str) -> list:
    if "=" not in statement:
        return []
    try:
        return check_problem("equation", statement, []).true_answer or []
    except Exception:  # noqa: BLE001
        return []


def format_example(ex: Optional[dict], lang: str = "ru") -> str:
    if not ex:
        return NO_EXAMPLE[lang]
    rows = [EXAMPLE_HEAD[lang], ex["statement"]]
    for i, line in enumerate(ex["reference"]):
        mark = "   " + ex["note"][lang] if i == ex.get("key_line") else ""
        rows.append(f"{i + 1}) {line}{mark}")
    rows.append(EXAMPLE_TAIL[lang])
    return "\n".join(rows)


def hint(first_error: dict, level: int, lang: str, statement: str, skill: Optional[str],
         seed: Optional[int] = None, family: Optional[str] = None) -> str:
    """Текст ступени 1–3 лестницы подсказок."""
    if level <= 1:
        return T.question_for(first_error, lang)
    if level == 2:
        return rule(first_error.get("tag") or "other", lang)
    return format_example(example(first_error, statement, skill, seed, family), lang)


# ---------------------------------------------------------------- «не называет ответ»

def _values(true_answer) -> list:
    if true_answer is None:
        return []
    if isinstance(true_answer, str):
        out = []
        for part in re.split(r"[;|]", true_answer.replace("−", "-")):
            part = part.strip().replace(",", ".")
            try:
                out.append(float(part))
            except ValueError:
                pass
        return out
    return [float(v) for v in true_answer]


def _fmt(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else f"{v:g}"


def leaks_answer(text: str, true_answer) -> bool:
    """Называет ли текст ответ: «x = 5», «x₁ = 0», «Ответ: 5», или перечисляет все корни."""
    vals = _values(true_answer)
    if not vals or not text:
        return False
    t = text.replace("−", "-").replace("–", "-")
    t = re.sub(r"(\d),(\d)", r"\1.\2", t)
    for v in vals:
        num = re.escape(_fmt(v))
        if re.search(rf"[A-Za-zА-Яа-я][₁₂12]?\s*=\s*{num}(?![\d.])", t):
            return True
        if re.search(rf"(ответ|жауап)[^\n]{{0,30}}(?<![\d.]){num}(?![\d.])", t, re.IGNORECASE):
            return True
    if len(vals) >= 2:
        nums = set(re.findall(r"(?<![\w.])-?\d+(?:\.\d+)?", t))
        if all(_fmt(v) in nums for v in vals):
            return True
    return False
